-- ============================================================================
-- 10. INTEGRACJA Z ISTNIEJĄCYMI TABELAMI WARSZTATOWYMI
-- Zachowanie istniejącej struktury jako moduł "Serwis"
-- ============================================================================

-- KLIENCI - pozostaje bez zmian, ale można dodać relację do CONTACTS
CREATE TABLE KLIENCI (
    ID_KLIENTA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    IMIE VARCHAR2(50) NOT NULL,
    NAZWISKO VARCHAR2(50) NOT NULL,
    TELEFON VARCHAR2(15) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    CONTACT_ID NUMBER, -- Opcjonalna relacja do CRM CONTACTS
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_KLIENT_CONTACT FOREIGN KEY (CONTACT_ID) REFERENCES CONTACTS(ID_CONTACT)
);

CREATE INDEX IDX_KLIENT_CONTACT ON KLIENCI(CONTACT_ID);

-- POJAZDY - pozostaje bez zmian
CREATE TABLE POJAZDY (
    ID_POJAZDU NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_KLIENTA NUMBER NOT NULL,
    MARKA VARCHAR2(50) NOT NULL,
    MODEL VARCHAR2(50) NOT NULL,
    ROK_PRODUKCJI NUMBER NOT NULL,
    NUMER_REJESTRACYJNY VARCHAR2(20) UNIQUE NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    FOREIGN KEY (ID_KLIENTA) REFERENCES KLIENCI(ID_KLIENTA) ON DELETE CASCADE
);

CREATE INDEX IDX_POJAZD_KLIENT ON POJAZDY(ID_KLIENTA);

-- ZLECENIA - rozszerzone o status_code i owner
CREATE TABLE ZLECENIA (
    ID_ZLECENIA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_POJAZDU NUMBER NOT NULL,
    DATA_PRZYJECIA DATE DEFAULT SYSDATE NOT NULL,
    OPIS_PROBLEMU CLOB NOT NULL,
    STATUS VARCHAR2(20) CHECK (STATUS IN ('Oczekuje', 'W trakcie', 'Zakończone')) NOT NULL,
    STATUS_CODE VARCHAR2(20), -- Nowy FK do słownika
    OWNER_ID NUMBER,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    FOREIGN KEY (ID_POJAZDU) REFERENCES POJAZDY(ID_POJAZDU) ON DELETE CASCADE,
    CONSTRAINT FK_ZLECENIE_STATUS FOREIGN KEY (STATUS_CODE) REFERENCES DICT_ORDER_STATUS(CODE),
    CONSTRAINT FK_ZLECENIE_OWNER FOREIGN KEY (OWNER_ID) REFERENCES USERS(ID_USER)
);

CREATE INDEX IDX_ZLECENIE_POJAZD ON ZLECENIA(ID_POJAZDU);
CREATE INDEX IDX_ZLECENIE_STATUS ON ZLECENIA(STATUS_CODE);
CREATE INDEX IDX_ZLECENIE_OWNER ON ZLECENIA(OWNER_ID);

-- Trigger dla POJAZDY (z oryginalnego skryptu)
CREATE OR REPLACE TRIGGER SPRAWDZ_ROK_PRODUKCJI
BEFORE INSERT OR UPDATE ON POJAZDY
FOR EACH ROW
BEGIN
    IF :NEW.ROK_PRODUKCJI < 1900 OR :NEW.ROK_PRODUKCJI > EXTRACT(YEAR FROM SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20001, 'Niepoprawny rok produkcji!');
    END IF;
END;
